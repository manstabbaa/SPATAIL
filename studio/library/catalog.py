"""catalog.py — the SPATAIL Starter Asset Library, as compact source data.

This is the single source of truth for the starter library. build_library.py
expands it into per-asset JSON manifests under public/assets/spatail-library/.

Encoding: each category has a `defaults` dict (fields shared by its assets) and a
list of `(id, name, [semanticTags], {overrides})` tuples. The builder merges
defaults + overrides into the full per-asset metadata schema. `fallbackPrimitive`
is always present (per asset or via the category default) so the runtime can build
a sensible proxy when no real GLB exists yet. Sizes are display sizes in metres
(the runtime rescales to the room); precision isn't critical for a starter set.

No Blender here — pure metadata. Real GLBs are generated on demand by the factory
and registered back via asset_library.register_generated().
"""
